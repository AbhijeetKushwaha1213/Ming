export async function ingestVideoTranscriptToRAG(video: VideoRecord, segments: TranscriptSegment[]): Promise<any> {
  if (!segments || segments.length === 0) return null;

  const formattedSegments = segments.map((s) => ({
    timestamp_start: s.start,
    timestamp_end: s.end,
    topic: s.topic || video.title,
    subtopic: s.subtopic || 'Lecture Content',
    text: s.text,
  }));

  const targetPath = video.storagePath || video.youtubeUrl || `video_${video.id}.mp4`;
  const jobId = `job_vid_${crypto.randomUUID().replace(/-/g, '').slice(0, 10)}`;

  const args = [
    'ingest',
    '--file', targetPath,
    '--type', 'VIDEO',
    '--user-id', video.userId,
    '--topic', video.title,
    '--subtopic', 'Lecture Content',
    '--source-id', video.id,
    '--document-id', video.id,
    '--job-id', jobId,
    '--transcript', JSON.stringify(formattedSegments),
  ];

  if (video.captionLanguage) {
    args.push('--caption-language', video.captionLanguage);
  }
  if (video.captionLanguageName) {
    args.push('--caption-language-name', video.captionLanguageName);
  }
  if (video.captionKind) {
    args.push('--caption-kind', video.captionKind);
  }
  if (video.captionProvider) {
    args.push('--caption-provider', video.captionProvider);
  }
  if (video.isAutoGenerated !== null && video.isAutoGenerated !== undefined) {
    args.push('--is-auto-generated', video.isAutoGenerated ? 'true' : 'false');
  }
  if (video.youtubeVideoId) {
    args.push('--youtube-video-id', video.youtubeVideoId);
  }
  if (video.durationSeconds > 0) {
    args.push('--verified-duration', String(video.durationSeconds));
  }

  const result = await runPythonCli(args, 90000);
  return result;
}

export async function processVideoJob(id: string, userId: string, customTranscript?: string | TranscriptSegment[]): Promise<VideoRecord> {
  const video = await getVideoById(id, userId);
  if (!video) throw new Error('Video not found or access denied');

  // Step: Updating status to processing
  await updateVideoStatus(id, userId, {
    status: 'processing',
    transcriptStatus: 'processing',
    extractionStatus: 'processing',
    errorMessage: null,
  });

  try {
    let segments: TranscriptSegment[] = [];
    let extractedMeta: Record<string, any> = {};
    let alreadyIndexedInCall1 = false;

    if (customTranscript) {
      segments = parseRawSegments(customTranscript);
      extractedMeta = {
        caption_kind: 'custom',
        is_auto_generated: false,
        caption_provider: 'custom_transcript',
        extraction_status: segments.length > 0 ? 'ready' : 'unavailable',
      };
    } else if (video.transcriptJson) {
      segments = parseRawSegments(video.transcriptJson);
    }

    // If no transcript yet, call RAG engine to extract verified captions/audio transcription & media metadata
    if (segments.length === 0) {
      if (video.sourceType === 'upload' && video.storagePath) {
        try {
          await fs.access(video.storagePath);
        } catch {
          throw new Error(`Uploaded video file not found at path: ${video.storagePath}`);
        }
      }

      const targetPath =
        video.storagePath ||
        video.youtubeUrl ||
        (video.youtubeVideoId ? `https://www.youtube.com/watch?v=${video.youtubeVideoId}` : video.title);

      const args = [
        'ingest',
        '--file', targetPath,
        '--type', 'VIDEO',
        '--user-id', video.userId,
        '--topic', video.title,
        '--subtopic', 'Key Concepts',
        '--source-id', video.id,
        '--document-id', video.id,
        '--job-id', `job_${video.id}`,
      ];
      if (video.youtubeVideoId) {
        args.push('--youtube-video-id', video.youtubeVideoId);
      }
      if (video.durationSeconds > 0) {
        args.push('--verified-duration', String(video.durationSeconds));
      }

      const ingestResult = await runPythonCli(args, 90000);
      extractedMeta = (ingestResult?.video_metadata && typeof ingestResult.video_metadata === 'object')
        ? ingestResult.video_metadata
        : {};
      alreadyIndexedInCall1 = Boolean(ingestResult && Number(ingestResult.chunk_count || 0) > 0);

      const earlyIsPlaceholder = !video.title || /^YouTube Lecture(?:\s*\([^)]+\))?$/i.test(video.title.trim());
      const earlyResolvedTitle = earlyIsPlaceholder && extractedMeta.title
        ? String(extractedMeta.title).trim()
        : video.title;

      if (ingestResult?.video_segments && Array.isArray(ingestResult.video_segments) && ingestResult.video_segments.length > 0) {
        segments = ingestResult.video_segments.map((seg: any) => {
          const segTopicRaw = typeof seg.topic === 'string' ? seg.topic.trim() : '';
          const segIsPlaceholder = !segTopicRaw || /^YouTube Lecture(?:\s*\([^)]+\))?$/i.test(segTopicRaw);
          return {
            start: Number(seg.start ?? 0),
            end: Number(seg.end ?? (seg.start ? seg.start + 30 : 60)),
            text: String(seg.text || ''),
            topic: !segIsPlaceholder ? segTopicRaw : earlyResolvedTitle,
            subtopic: seg.subtopic || 'Lecture Content',
          };
        });
      } else if (ingestResult?.preview_chunks && Array.isArray(ingestResult.preview_chunks) && ingestResult.preview_chunks.length > 0) {
        segments = ingestResult.preview_chunks.map((pc: any) => {
          const pcTopicRaw = typeof pc.topic === 'string' ? pc.topic.trim() : '';
          const pcIsPlaceholder = !pcTopicRaw || /^YouTube Lecture(?:\s*\([^)]+\))?$/i.test(pcTopicRaw);
          return {
            start: Number(pc.timestamp_start ?? 0),
            end: Number(pc.timestamp_end ?? (pc.timestamp_start ? pc.timestamp_start + 30 : 60)),
            text: String(pc.text || pc.snippet || ''),
            topic: !pcIsPlaceholder ? pcTopicRaw : earlyResolvedTitle,
            subtopic: pc.subtopic || 'Lecture Content',
          };
        });
      }
    }

    const isPlaceholderTitle = !video.title || /^YouTube Lecture(?:\s*\([^)]+\))?$/i.test(video.title.trim());
    const resolvedTitle = isPlaceholderTitle && extractedMeta.title
      ? String(extractedMeta.title).trim()
      : video.title;
    const metaDuration = Number(extractedMeta.duration_seconds || 0);
    const resolvedDuration = metaDuration > 0
      ? metaDuration
      : (video.durationSeconds > 0 ? video.durationSeconds : 0);

    const commonMetaUpdates: Partial<VideoRecord> = {
      title: resolvedTitle,
      channelName: extractedMeta.channel ? String(extractedMeta.channel) : video.channelName,
      durationSource: extractedMeta.duration_source ? String(extractedMeta.duration_source) : video.durationSource,
      thumbnailUrl: extractedMeta.thumbnail_url ? String(extractedMeta.thumbnail_url) : video.thumbnailUrl,
      captionLanguage: extractedMeta.caption_language ? String(extractedMeta.caption_language) : video.captionLanguage,
      captionLanguageName: extractedMeta.caption_language_name ? String(extractedMeta.caption_language_name) : video.captionLanguageName,
      captionKind: extractedMeta.caption_kind ? String(extractedMeta.caption_kind) : video.captionKind,
      isAutoGenerated: extractedMeta.is_auto_generated !== undefined && extractedMeta.is_auto_generated !== null
        ? Boolean(extractedMeta.is_auto_generated)
        : video.isAutoGenerated,
      captionProvider: extractedMeta.caption_provider ? String(extractedMeta.caption_provider) : video.captionProvider,
    };

    // Validate source identity & segments strictly against resolved media duration and synthetic template rules
    const extractedVideoIdMismatch =
      video.sourceType === 'youtube' &&
      video.youtubeVideoId &&
      extractedMeta.video_id &&
      String(extractedMeta.video_id) !== video.youtubeVideoId
        ? `Extracted metadata video ID (${extractedMeta.video_id}) does not match stored video ID (${video.youtubeVideoId})`
        : null;

    const mismatchReason =
      extractedVideoIdMismatch ||
      isKnownMismatchedVideoRecord(
        {
          id: video.id,
          title: resolvedTitle,
          youtubeUrl: video.youtubeUrl,
          youtubeVideoId: video.youtubeVideoId,
          durationSeconds: resolvedDuration,
        },
        segments
      );

    const validation = mismatchReason
      ? { valid: false, error: mismatchReason }
      : segments.length > 0
      ? validateTranscriptSegments(segments, resolvedDuration > 0 ? resolvedDuration : undefined)
      : { valid: false, error: 'No caption or speech segments available' };

    if (validation.valid && validation.segments && validation.segments.length > 0) {
      const verifiedSegments = validation.segments;
      const maxEnd = verifiedSegments.reduce((m, s) => Math.max(m, s.end), 0);

      if (!alreadyIndexedInCall1) {
        const videoWithMeta: VideoRecord = {
          ...video,
          ...commonMetaUpdates,
          title: resolvedTitle,
          durationSeconds: resolvedDuration > 0 ? resolvedDuration : maxEnd,
        };
        await ingestVideoTranscriptToRAG(videoWithMeta, verifiedSegments);
      }

      const updated = await updateVideoStatus(id, userId, {
        ...commonMetaUpdates,
        status: 'ready',
        transcriptStatus: 'ready',
        extractionStatus: String(extractedMeta.extraction_status || 'ready'),
        transcriptJson: JSON.stringify(verifiedSegments),
        durationSeconds: resolvedDuration > 0 ? resolvedDuration : maxEnd,
        errorMessage: null,
      });
      return updated!;
    }

    // Purge any derived vectors when no valid transcript exists or validation failed
    if (alreadyIndexedInCall1 || mismatchReason || (segments.length > 0 && !validation.valid)) {
      try {
        await runPythonCli(['delete-source', '--source-id', video.id, '--user-id', video.userId]);
      } catch (purgeErr) {
        console.warn('Vector purge warning after failed validation:', purgeErr);
      }
    }

    // Real transcript is unavailable (or rejected by bounds validation) — preserve metadata honestly
    const unavailableStatus = (segments.length > 0 && !validation.valid)
      ? 'failed'
      : String(extractedMeta.extraction_status || 'unavailable');
    const unavailableErr = (segments.length > 0 && !validation.valid)
      ? (validation.error || 'Transcript failed integrity validation')
      : (extractedMeta.error ? String(extractedMeta.error) : null);

    const updated = await updateVideoStatus(id, userId, {
      ...commonMetaUpdates,
      status: 'ready',
      transcriptStatus: 'unavailable',
      extractionStatus: unavailableStatus,
      transcriptJson: null,
      durationSeconds: resolvedDuration,
      errorMessage: unavailableErr,
    });
    return updated!;
  } catch (err: any) {
    console.error('Video processing job error:', err);
    const failed = await updateVideoStatus(id, userId, {
      status: 'failed',
      transcriptStatus: 'failed',
      extractionStatus: 'failed',
      errorMessage: err.message || 'Processing failed',
    });
    return failed!;
  }
}

export async function askVideoQuestion(
  id: string,
  userId: string,
  question: string,
  history: Array<{ role: string; content: string }> = [],
  language: string = 'english'
): Promise<any> {
  const video = await getVideoById(id, userId);
  if (!video) {
    throw new Error('Video not found or access denied');
  }

  // If no verified transcript is available, refuse to fabricate citations or claim grounded support
  if (video.transcriptStatus !== 'ready' || !video.transcriptJson) {
    return {
      success: true,
      videoId: video.id,
      question,
      response: `A verified transcript is not available for "${video.title}". I cannot cite specific timestamps or claim transcript-grounded evidence. For general questions on this topic, I can provide conceptual assistance, but lecture-specific claims cannot be verified against this media.`,
      citations: [],
      grounded: false,
      insufficient_evidence: true,
    };
  }

  // Parse and validate stored transcript segments and source identity
  let verifiedSegments: TranscriptSegment[] = [];
  try {
    const rawParsed = JSON.parse(video.transcriptJson);
    const urlYtId = video.youtubeUrl ? extractYouTubeId(video.youtubeUrl, false) : null;
    const urlIdConflict =
      video.sourceType === 'youtube' &&
      video.youtubeUrl &&
      video.youtubeVideoId &&
      urlYtId &&
      urlYtId !== video.youtubeVideoId
        ? `Source mismatch: youtubeUrl (${urlYtId}) differs from youtubeVideoId (${video.youtubeVideoId})`
        : null;
    const mismatchReason = urlIdConflict || isKnownMismatchedVideoRecord(video, rawParsed);
    const validation = mismatchReason
      ? { valid: false, error: mismatchReason }
      : validateTranscriptSegments(rawParsed, video.durationSeconds);

    if (!validation.valid || !validation.segments) {
      // Invalidate compromised stored transcript in database and purge derived chunks
      await updateVideoStatus(id, userId, {
        transcriptStatus: 'unavailable',
        transcriptJson: null,
      });
      try {
        await runPythonCli(['delete-source', '--source-id', video.id, '--user-id', video.userId]);
      } catch (purgeErr) {
        console.warn('Vector purge warning on askVideoQuestion:', purgeErr);
      }
      return {
        success: true,
        videoId: video.id,
        question,
        response: `The stored transcript for "${video.title}" failed source integrity verification (${validation.error}). Citations have been withheld.`,
        citations: [],
        grounded: false,
        insufficient_evidence: true,
      };
    }
    verifiedSegments = validation.segments;
  } catch {
    await updateVideoStatus(id, userId, {
      transcriptStatus: 'unavailable',
      transcriptJson: null,
    });
    try {
      await runPythonCli(['delete-source', '--source-id', video.id, '--user-id', video.userId]);
    } catch (purgeErr) {
      console.warn('Vector purge warning on malformed transcript:', purgeErr);
    }
    return {
      success: true,
      videoId: video.id,
      question,
      response: `The transcript for "${video.title}" could not be parsed. Citations have been withheld.`,
      citations: [],
      grounded: false,
      insufficient_evidence: true,
    };
  }

  const args = [
    'chat',
    '--query', question,
    '--user-id', userId,
    '--source-id', video.id,
    '--topic', video.title,
    '--history', JSON.stringify(history),
    '--language', language,
    '--min-confidence', '0.45',
  ];

  const response = await runPythonCli(args, 65000);

  // Revalidate citations server-side against verified transcript segments and media duration
  if (response && Array.isArray(response.citations)) {
    const validCitations: any[] = [];
    const rejectedEvidenceIds = new Set<string>();
    const rejectedTimeLabels = new Set<string>();

    for (const c of response.citations) {
      const hasTime = c.timestamp_start !== null && c.timestamp_start !== undefined && c.timestamp_start >= 0;
      const startSec = hasTime ? Number(c.timestamp_start) : Number(c.seek_seconds ?? 0);
      const endSec = Number(c.timestamp_end ?? (startSec + 30));
      const evId = String(c.evidence_id || '');
      const formattedTime = formatTimestamp(startSec);

      // Reject citations belonging to another source or YouTube video
      if (
        (c.source_id && String(c.source_id) !== video.id) ||
        (c.document_id && String(c.document_id) !== video.id) ||
        (c.youtube_video_id && video.youtubeVideoId && String(c.youtube_video_id) !== video.youtubeVideoId)
      ) {
        if (evId) rejectedEvidenceIds.add(evId);
        rejectedTimeLabels.add(formattedTime);
        continue;
      }

      if (!isFinite(startSec) || startSec < 0) {
        if (evId) rejectedEvidenceIds.add(evId);
        rejectedTimeLabels.add(formattedTime);
        continue;
      }

      // Reject citations exceeding verified media duration (NEVER clamp!)
      if (
        video.durationSeconds > 0 &&
        (startSec > video.durationSeconds + MEDIA_START_TOLERANCE_SECONDS ||
          endSec > video.durationSeconds + CAPTION_CUE_END_TOLERANCE_SECONDS)
      ) {
        if (evId) rejectedEvidenceIds.add(evId);
        rejectedTimeLabels.add(formattedTime);
        continue;
      }

      // Verify that this timestamp actually falls within existing segment(s) in verifiedSegments
      const matchingSegments = verifiedSegments.filter(
        (seg) => seg.end >= startSec - 2.0 && seg.start <= endSec + 2.0
      );
      if (matchingSegments.length === 0) {
        if (evId) rejectedEvidenceIds.add(evId);
        rejectedTimeLabels.add(formattedTime);
        continue;
      }

      // Requirement 4: Answer integrity
      // A timestamp falling within the video duration does not prove claim support.
      // Note: Query-term overlap is a fast relevance heuristic for rejecting completely disjoint inquiries;
      // it does not by itself prove full semantic claim support or propositional entailment.
      const stopSet = new Set([
        'what', 'which', 'where', 'when', 'why', 'how', 'does', 'did', 'are', 'was', 'were',
        'explain', 'tell', 'about', 'this', 'that', 'from', 'with', 'into', 'video', 'lecture',
        'mentioned', 'minute', 'minutes', 'second', 'seconds', 'mean', 'means', 'meaning',
        'used', 'use', 'say', 'says', 'said', 'the', 'and', 'for', 'its', 'can', 'concept',
        'concepts', 'key', 'overview', 'summary', 'main', 'point', 'points', 'topics', 'topic'
      ]);
      const isOverviewQuestion = /\b(key concept|key concepts|overview|summary|summarize|recap|main point|main points|what is this video about|what is this lecture about|what was discussed)\b/i.test(question);
      const queryWords = question
        .toLowerCase()
        .replace(/[^a-z0-9\s]/g, ' ')
        .split(/\s+/)
        .filter((w) => w.length >= 3 && !stopSet.has(w));

      const joinedVerbatimText = matchingSegments.map((s) => s.text).join(' ');
      const transliteratedText = transliterateDevanagariToLatin(joinedVerbatimText);
      const evidenceSearchText = [
        joinedVerbatimText,
        transliteratedText,
        String(c.snippet || ''),
        String(c.english_gloss || ''),
      ]
        .join(' ')
        .toLowerCase();

      const hasTopicOverlap =
        isOverviewQuestion ||
        queryWords.length === 0 ||
        queryWords.some((w) => {
          if (evidenceSearchText.includes(w)) return true;
          if (w.length >= 6 && evidenceSearchText.includes(w.slice(0, w.length - 3))) return true;
          return false;
        });

      // Also check if the query specifically requested an out-of-bounds timestamp (e.g. at 8 minutes on 3:39/3:40 video)
      const queryTimeMatch = question.match(/(\d{1,2}):(\d{2})|(\d+)\s*(?:m|min|minute)/i);
      let queryRequestedTime = -1;
      if (queryTimeMatch) {
        if (queryTimeMatch[1] && queryTimeMatch[2]) {
          queryRequestedTime = parseInt(queryTimeMatch[1], 10) * 60 + parseInt(queryTimeMatch[2], 10);
        } else if (queryTimeMatch[3]) {
          queryRequestedTime = parseInt(queryTimeMatch[3], 10) * 60;
        }
      }
      const queryTimeOutOfBounds = video.durationSeconds > 0 && queryRequestedTime > video.durationSeconds + CAPTION_CUE_END_TOLERANCE_SECONDS;

      if (!hasTopicOverlap || queryTimeOutOfBounds) {
        if (evId) rejectedEvidenceIds.add(evId);
        rejectedTimeLabels.add(formattedTime);
        continue;
      }

      validCitations.push({
        ...c,
        seek_seconds: startSec,
        timestamp_start: startSec,
        timestamp_end: endSec,
        formatted_timestamp: formattedTime,
        citation_label: `[${formattedTime}]`,
        snippet: c.snippet || matchingSegments[0].text.slice(0, 140),
      });
    }

    response.citations = validCitations;
    response.grounded = validCitations.length > 0;

    // Requirement 4: Answer integrity
    // A timestamp falling within duration does not prove claim support.
    // If all citations are rejected or no valid evidence remains, return an insufficient-evidence response.
    if (!response.grounded || validCitations.length === 0) {
      response.insufficient_evidence = true;
      response.grounded = false;
      response.citations = [];
      response.response = `The lecture "${video.title}" does not contain verified transcript evidence to answer this question. The cited references fall outside the verified lecture content.`;
    } else if (rejectedEvidenceIds.size > 0 || rejectedTimeLabels.size > 0) {
      // If some citations were rejected, strip unsupported claims associated with those rejected citations
      if (typeof response.response === 'string') {
        const blocks = response.response.split(/\n{2,}/);
        const filteredBlocks = blocks.filter((block) => {
          for (const evId of rejectedEvidenceIds) {
            if (block.includes(`[${evId}]`)) return false;
          }
          for (const label of rejectedTimeLabels) {
            if (block.includes(`[${label}]`) || block.includes(`(${label})`)) return false;
          }
          return true;
        });

        if (filteredBlocks.length > 0) {
          response.response = filteredBlocks.join('\n\n');
        } else {
          response.insufficient_evidence = true;
          response.grounded = false;
          response.citations = [];
          response.response = `The lecture "${video.title}" does not contain verified transcript evidence to answer this question. The cited claims fall outside the verified lecture content.`;
        }
      }
    }
  }

  // Clean internal raw chunk references from response text so students see clean prose
  if (response && typeof response.response === 'string') {
    response.response = response.response
      .replace(/\[CHUNK\s+[^\]]+\]/g, '')
      .replace(/\[[a-zA-Z0-9_\-]+_t\d+_c\d+\]/g, '')
      .replace(/\[vid_[a-zA-Z0-9_\-]+\]/g, '')
      .replace(/[ \t]+\n/g, '\n')
      .replace(/\n{3,}/g, '\n\n')
      .trim();
  }

  return response;
}

function mapDbToVideo(row: any): VideoRecord {
  return {
    id: row.id,
    userId: row.userId,
    title: row.title,
    sourceType: row.sourceType as 'youtube' | 'upload',
    youtubeUrl: row.youtubeUrl || null,
    youtubeVideoId: row.youtubeVideoId || null,
    storagePath: row.storagePath || null,
    fileUrl: row.fileUrl || null,
    status: row.status as 'pending' | 'processing' | 'ready' | 'failed',
    durationSeconds: Number(row.durationSeconds || 0),
    thumbnailUrl: row.thumbnailUrl || null,
    transcriptStatus: row.transcriptStatus as TranscriptStatus,
    transcriptJson: row.transcriptJson || null,
    errorMessage: row.errorMessage || null,
    channelName: row.channelName || null,
    durationSource: row.durationSource || null,
    captionLanguage: row.captionLanguage || null,
    captionLanguageName: row.captionLanguageName || null,
    captionKind: row.captionKind || null,
    isAutoGenerated: row.isAutoGenerated === null || row.isAutoGenerated === undefined ? null : Boolean(row.isAutoGenerated),
    captionProvider: row.captionProvider || null,
    extractionStatus: row.extractionStatus || null,
    createdAt: typeof row.createdAt === 'string' ? row.createdAt : row.createdAt?.toISOString?.() || new Date(row.createdAt).toISOString(),
    updatedAt: typeof row.updatedAt === 'string' ? row.updatedAt : row.updatedAt?.toISOString?.() || new Date(row.updatedAt).toISOString(),
  };
}
