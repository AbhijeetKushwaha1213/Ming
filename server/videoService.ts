const YOUTUBE_ALLOWED_HOSTS = new Set([
  'youtube.com',
  'www.youtube.com',
  'm.youtube.com',
  'music.youtube.com',
  'youtu.be',
  'www.youtu.be',
  'youtube-nocookie.com',
  'www.youtube-nocookie.com',
]);

const YOUTUBE_ID_RE = /^[a-zA-Z0-9_-]{11}$/;
const KNOWN_LEGACY_CORRUPTED_IDS = new Set([
  'vid_sample_mit_linear_algebra',
  'vid_sample_3blue1brown_calculus',
]);

function extractVideoIdFromUrlObject(urlObj: URL): string | null {
  if (urlObj.protocol !== 'http:' && urlObj.protocol !== 'https:') return null;
  const host = urlObj.hostname.toLowerCase();
  if (!YOUTUBE_ALLOWED_HOSTS.has(host)) return null;
  const pathParts = urlObj.pathname.split('/').filter(Boolean);

  if (host === 'youtu.be' || host === 'www.youtu.be') {
    return pathParts.length >= 1 && YOUTUBE_ID_RE.test(pathParts[0]) ? pathParts[0] : null;
  }

  if (pathParts.length === 0 || pathParts[0] === 'watch') {
    const vParam = urlObj.searchParams.get('v');
    return vParam && YOUTUBE_ID_RE.test(vParam) ? vParam : null;
  }

  if (
    pathParts.length >= 2 &&
    (pathParts[0] === 'embed' ||
      pathParts[0] === 'shorts' ||
      pathParts[0] === 'v' ||
      pathParts[0] === 'live') &&
    YOUTUBE_ID_RE.test(pathParts[1])
  ) {
    return pathParts[1];
  }

  return null;
}

function parseSingleYouTubeUrlCandidate(rawUrl: string): { videoId: string; canonicalUrl: string } | null {
  const cleaned = rawUrl.trim();
  if (!cleaned || /\s/.test(cleaned)) return null;

  const normalizedScheme = /^(youtu\.be|(?:www\.|m\.|music\.)?youtube\.com|(?:www\.)?youtube-nocookie\.com)\//i.test(cleaned)
    ? `https://${cleaned}`
    : cleaned;

  try {
    const parsed = new URL(normalizedScheme);
    const id = extractVideoIdFromUrlObject(parsed);
    if (!id) return null;
    return {
      videoId: id,
      canonicalUrl: `https://www.youtube.com/watch?v=${id}`,
    };
  } catch {
    return null;
  }
}

function looksLikeUrlText(text: string): boolean {
  const t = text.trim();
  return (
    /^https?:\/\//i.test(t) ||
    /(?:^|\s)(?:www\.|m\.|music\.)?(?:youtube\.com|youtu\.be|youtube-nocookie\.com)\b/i.test(t) ||
    /\.[a-z]{2,}\//i.test(t)
  );
}

export function parseYouTubeInput(
  input: string,
  options: { allowBareId?: boolean } = {}
): YouTubeParseResult {
  const { allowBareId = false } = options;

  if (!input || typeof input !== 'string') {
    return { valid: false, videoId: null, canonicalUrl: null, error: 'YouTube URL is required' };
  }

  const trimmed = input.trim();
  if (!trimmed) {
    return { valid: false, videoId: null, canonicalUrl: null, error: 'YouTube URL is required' };
  }

  if (trimmed.startsWith('<') || trimmed.endsWith('>')) {
    const autoMatch = trimmed.match(/^<([^<>\s]+)>$/);
    if (!autoMatch) {
      return { valid: false, videoId: null, canonicalUrl: null, error: 'Malformed Markdown YouTube link' };
    }
    const inner = parseSingleYouTubeUrlCandidate(autoMatch[1]);
    if (!inner) {
      return { valid: false, videoId: null, canonicalUrl: null, error: 'Invalid YouTube URL inside link brackets' };
    }
    return { valid: true, videoId: inner.videoId, canonicalUrl: inner.canonicalUrl, wasMarkdown: true };
  }

  if (trimmed.includes('[') || trimmed.includes(']')) {
    const mdMatch = trimmed.match(/^\[([^\]]*)\]\(([^)]+)\)$/);
    if (!mdMatch) {
      return { valid: false, videoId: null, canonicalUrl: null, error: 'Malformed Markdown YouTube link' };
    }
    const label = mdMatch[1].trim();
    let destRaw = mdMatch[2].trim();
    const destWithTitleMatch = destRaw.match(/^<([^>\s]+)>|^(\S+)(?:\s+["'(].*["')])?$/);
    if (!destWithTitleMatch) {
      return { valid: false, videoId: null, canonicalUrl: null, error: 'Malformed Markdown link destination URL' };
    }
    destRaw = destWithTitleMatch[1] || destWithTitleMatch[2] || '';
    const destParsed = parseSingleYouTubeUrlCandidate(destRaw);
    if (!destParsed) {
      return { valid: false, videoId: null, canonicalUrl: null, error: 'Invalid Markdown YouTube link destination' };
    }
    if (label && looksLikeUrlText(label)) {
      const labelParsed = parseSingleYouTubeUrlCandidate(label);
      if (!labelParsed || labelParsed.videoId !== destParsed.videoId) {
        return {
          valid: false,
          videoId: null,
          canonicalUrl: null,
          error: 'Markdown link label and destination point to different URLs or videos',
        };
      }
    }
    return { valid: true, videoId: destParsed.videoId, canonicalUrl: destParsed.canonicalUrl, wasMarkdown: true };
  }

  if (trimmed.includes('(') || trimmed.includes(')') || /\s/.test(trimmed)) {
    return { valid: false, videoId: null, canonicalUrl: null, error: 'Invalid or malformed YouTube URL' };
  }

  if (YOUTUBE_ID_RE.test(trimmed)) {
    if (!allowBareId) {
      return { valid: false, videoId: null, canonicalUrl: null, error: 'Full YouTube URL is required' };
    }
    return {
      valid: true,
      videoId: trimmed,
      canonicalUrl: `https://www.youtube.com/watch?v=${trimmed}`,
      wasMarkdown: false,
    };
  }

  const parsedUrl = parseSingleYouTubeUrlCandidate(trimmed);
  if (!parsedUrl) {
    return { valid: false, videoId: null, canonicalUrl: null, error: 'Invalid YouTube URL format' };
  }
  return { valid: true, videoId: parsedUrl.videoId, canonicalUrl: parsedUrl.canonicalUrl, wasMarkdown: false };
}

export function normalizeYouTubeUrl(url: string, allowBareId = false): string | null {
  return parseYouTubeInput(url, { allowBareId }).canonicalUrl;
}

export function extractYouTubeId(url: string, allowBareId = true): string | null {
  return parseYouTubeInput(url, { allowBareId }).videoId;
}

export function isValidYouTubeUrl(url: string, allowBareId = false): boolean {
  return parseYouTubeInput(url, { allowBareId }).valid;
}

export function isKnownMismatchedVideoRecord(
  video: {
    id?: string;
    title?: string | null;
    youtubeUrl?: string | null;
    youtubeVideoId?: string | null;
    durationSeconds?: number | null;
  },
  rawSegments?: any[]
): string | null {
  if (!video) return 'Missing video record';
  if (video.id && KNOWN_LEGACY_CORRUPTED_IDS.has(video.id)) {
    return 'Legacy unverified sample record with fabricated transcript metadata';
  }
  const urlId = video.youtubeUrl ? extractYouTubeId(video.youtubeUrl, false) : null;
  const ytId = video.youtubeVideoId || urlId;
  if (ytId === '7UJ4CFRGd-U') {
    const title = String(video.title || '');
    const dur = Number(video.durationSeconds || 0);
    if (/MIT\s*18\.06|Geometry of Linear Equations/i.test(title)) {
      return 'Source mismatch: video ID 7UJ4CFRGd-U is a 7:34 interview, not MIT 18.06 Lecture 1';
    }
    if (dur > 480) {
      return `Duration mismatch: stored duration (${formatTimestamp(dur)}) exceeds 7UJ4CFRGd-U actual runtime (~7:34)`;
    }
    if (Array.isArray(rawSegments)) {
      const hasFabricatedMitLine = rawSegments.some(
        (s) =>
          typeof s?.text === 'string' &&
          /The row picture versus the column picture of linear systems|Fundamental theorem/i.test(s.text)
      );
      if (hasFabricatedMitLine) {
        return 'Transcript mismatch: segments belong to another lecture and not video 7UJ4CFRGd-U';
      }
    }
  }
  return null;
}

export function formatTimestamp(seconds: number): string {
  const s = Math.max(0, Math.floor(seconds || 0));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const remSec = s % 60;
  if (h > 0) {
    return `${h}:${m.toString().padStart(2, '0')}:${remSec.toString().padStart(2, '0')}`;
  }
  return `${m}:${remSec.toString().padStart(2, '0')}`;
}

export function parseTimestampString(timeStr: string): number {
  if (!timeStr) return 0;
  const parts = timeStr.replace(/[\[\]]/g, '').trim().split(':').map(Number);
  if (parts.some(isNaN)) return 0;
  if (parts.length === 3) {
    return parts[0] * 3600 + parts[1] * 60 + parts[2];
  }
  if (parts.length === 2) {
    return parts[0] * 60 + parts[1];
  }
  if (parts.length === 1) {
    return parts[0];
  }
  return 0;
}

export interface TranscriptValidationResult {
  valid: boolean;
  error?: string;
  segments?: TranscriptSegment[];
}

/**
 * Validates transcript segments against media duration and source integrity.
 * Materially invalid timestamps (e.g. end > duration) are REJECTED, NEVER clamped.
 * Synthetic placeholder outlines masquerading as verbatim transcripts are also rejected.
 */
export function validateTranscriptSegments(
  rawSegments: any[],
  durationSeconds?: number
): TranscriptValidationResult {
  if (!Array.isArray(rawSegments) || rawSegments.length === 0) {
    return { valid: false, error: 'Transcript segment list is empty or not an array' };
  }

  const duration = durationSeconds && durationSeconds > 0 ? Number(durationSeconds) : null;
  const sanitized: TranscriptSegment[] = [];

  for (let i = 0; i < rawSegments.length; i++) {
    const s = rawSegments[i];
    if (!s || typeof s !== 'object') {
      return { valid: false, error: `Segment ${i + 1} is not a valid object` };
    }

    const start = Number(s.start ?? s.timestamp_start);
    const end = Number(s.end ?? s.timestamp_end);
    const text = String(s.text ?? '').trim();

    if (!isFinite(start) || start < 0) {
      return { valid: false, error: `Segment ${i + 1} has invalid or negative start timestamp (${start})` };
    }
    if (!isFinite(end) || end <= start) {
      return { valid: false, error: `Segment ${i + 1} end timestamp (${end}) must be strictly greater than start (${start})` };
    }
    if (!text) {
      return { valid: false, error: `Segment ${i + 1} has empty transcript text` };
    }

    // Strict bounds check: reject out-of-bounds segments; NEVER clamp!
    // Allows integer-duration rounding (<= 1.5s) and trailing ASR caption window fadeout (<= 3.0s).
    if (duration !== null) {
      if (start > duration + MEDIA_START_TOLERANCE_SECONDS) {
        return {
          valid: false,
          error: `Segment ${i + 1} start (${formatTimestamp(start)} / ${start}s) exceeds verified media duration (${formatTimestamp(duration)} / ${duration}s)`,
        };
      }
      if (end > duration + CAPTION_CUE_END_TOLERANCE_SECONDS) {
        return {
          valid: false,
          error: `Segment ${i + 1} end (${formatTimestamp(end)} / ${end}s) exceeds verified media duration (${formatTimestamp(duration)} / ${duration}s)`,
        };
      }
    }

    // Check for known synthetic placeholder outlines
    const subtopic = String(s.subtopic || '');
    if (
      subtopic === 'Detailed Walkthrough' ||
      subtopic === 'Summary & Practice' ||
      subtopic === 'Step-by-Step Flow' ||
      subtopic === 'Core Mechanisms' ||
      /Overview of core architectural concepts, prerequisites/i.test(text) ||
      /Core principles, definitions, and foundational concepts explained in/i.test(text) ||
      /Step-by-step mathematical derivation, code walkthrough/i.test(text) ||
      /Review, examination takeaways, summary points, and best practices for/i.test(text)
    ) {
      return {
        valid: false,
        error: `Segment ${i + 1} contains synthetic placeholder template text masquerading as verbatim transcript evidence`,
      };
    }

    sanitized.push({
      start,
      end,
      text,
      topic: s.topic ? String(s.topic) : undefined,
      subtopic: s.subtopic ? String(s.subtopic) : undefined,
    });
  }

  // Ensure chronological order
  for (let i = 1; i < sanitized.length; i++) {
    if (sanitized[i].start < sanitized[i - 1].start) {
      return {
        valid: false,
        error: `Segment ${i + 1} start (${sanitized[i].start}s) is earlier than preceding segment start (${sanitized[i - 1].start}s)`,
      };
    }
  }

  return { valid: true, segments: sanitized };
}

export function isSyntheticOrInvalidTranscript(
  rawSegments: any[],
  durationSeconds?: number
): boolean {
  return !validateTranscriptSegments(rawSegments, durationSeconds).valid;
}

let sanitizeOncePromise: Promise<number> | null = null;

function ensureSanitizedOnce(): Promise<number> {
  if (!sanitizeOncePromise) {
    sanitizeOncePromise = sanitizeVideoTranscripts();
  }
  return sanitizeOncePromise;
}

/**
 * Invalidate derived synthetic transcripts or invalid out-of-bounds transcripts in database.
 * Does NOT delete original user uploads or unrelated learner data.
 */
export async function sanitizeVideoTranscripts(): Promise<number> {
  await ensureVideoSchema();
  try {
    const rows = await prisma.$queryRawUnsafe<any[]>(
      'SELECT id, userId, title, youtubeUrl, youtubeVideoId, durationSeconds, transcriptStatus, transcriptJson FROM videos'
    );
    let cleanedCount = 0;
    const purgeByUser = new Map<string, string[]>();

    const queueVectorPurge = (userId: string, videoId: string) => {
      if (!userId || !videoId) return;
      const list = purgeByUser.get(userId) || [];
      if (!list.includes(videoId)) list.push(videoId);
      purgeByUser.set(userId, list);
    };

    for (const row of rows) {
      if (row.transcriptStatus === 'ready') {
        let isInvalid = false;
        let parsedSegs: any[] | undefined;
        if (!row.transcriptJson) {
          isInvalid = true;
        } else {
          try {
            const segs = JSON.parse(row.transcriptJson);
            parsedSegs = Array.isArray(segs) ? segs : undefined;
            const val = validateTranscriptSegments(segs, Number(row.durationSeconds || 0));
            if (!val.valid) {
              isInvalid = true;
            }
          } catch {
            isInvalid = true;
          }
        }

        const urlYtId = row.youtubeUrl ? extractYouTubeId(String(row.youtubeUrl), false) : null;
        if (row.youtubeUrl && row.youtubeVideoId && urlYtId && urlYtId !== row.youtubeVideoId) {
          isInvalid = true;
        }
        if (isKnownMismatchedVideoRecord(row, parsedSegs)) {
          isInvalid = true;
        }

        if (isInvalid) {
          cleanedCount++;
          await prisma.$executeRawUnsafe(
            "UPDATE videos SET transcriptStatus = 'unavailable', transcriptJson = NULL, updatedAt = ? WHERE id = ?",
            new Date(),
            row.id
          );
          queueVectorPurge(String(row.userId), String(row.id));
        }
      } else if (row.transcriptStatus !== 'processing') {
        // Ensure unavailable/failed videos never leave stale orphaned vectors in ChromaDB
        queueVectorPurge(String(row.userId), String(row.id));
      }
    }

    for (const [uId, sIds] of purgeByUser.entries()) {
      if (sIds.length === 0) continue;
      try {
        await runPythonCli(['delete-source', '--source-id', sIds.join(','), '--user-id', uId]);
      } catch (err) {
        console.warn('Vector purge warning on sanitize:', err);
      }
    }

    return cleanedCount;
  } catch (err) {
    console.warn('Transcript sanitization warning:', err);
    return 0;
  }
}

function parseRawSegments(raw: unknown): TranscriptSegment[] {
  if (!raw) return [];
  if (Array.isArray(raw)) {
    return raw.map((item: any) => ({
      start: Number(item.start ?? item.timestamp_start ?? 0),
      end: Number(item.end ?? item.timestamp_end ?? 30),
      text: String(item.text ?? '').trim(),
      topic: item.topic ? String(item.topic) : undefined,
      subtopic: item.subtopic ? String(item.subtopic) : undefined,
    })).filter((s) => Boolean(s.text));
  }
  if (typeof raw === 'string') {
    const trimmed = raw.trim();
    if (trimmed.startsWith('[') || trimmed.startsWith('{')) {
      try {
        const parsed = JSON.parse(trimmed);
        return parseRawSegments(parsed);
      } catch {
        // Fall back to line parser
      }
    }

    const segments: TranscriptSegment[] = [];
    const lines = trimmed.split('\n');
    let currentStart = 0;
    let currentText: string[] = [];

    for (const line of lines) {
      const match = line.match(/\[?(\d{1,2}):(\d{2})(?::(\d{2}))?\]?/);
      if (match) {
        const h = match[3] ? parseInt(match[1], 10) : 0;
        const m = match[3] ? parseInt(match[2], 10) : parseInt(match[1], 10);
        const s = match[3] ? parseInt(match[3], 10) : parseInt(match[2], 10);
        const newTime = h * 3600 + m * 60 + s;

        if (currentText.length > 0) {
          segments.push({
            start: currentStart,
            end: newTime,
            text: currentText.join(' '),
          });
          currentText = [];
        }
        currentStart = newTime;
        const cleanContent = line.replace(/\[?(\d{1,2}):(\d{2})(?::(\d{2}))?\]?/, '').trim();
        if (cleanContent) currentText.push(cleanContent);
      } else {
        const clean = line.trim();
        if (clean) currentText.push(clean);
      }
    }

    if (currentText.length > 0) {
      segments.push({
        start: currentStart,
        end: currentStart + 45,
        text: currentText.join(' '),
      });
    }

    return segments;
  }
  return [];
}

export async function createVideoRecord(input: CreateVideoInput): Promise<VideoRecord> {
  await ensureVideoSchema();
  await ensureSanitizedOnce();

  const id = `vid_${crypto.randomUUID().replace(/-/g, '').slice(0, 16)}`;
  let youtubeUrl = input.youtubeUrl || null;
  let youtubeVideoId: string | null = input.youtubeVideoId || null;
  let thumbnailUrl = input.thumbnailUrl || null;

  if (input.sourceType === 'youtube' && input.youtubeUrl) {
    const parsedYt = parseYouTubeInput(input.youtubeUrl, { allowBareId: false });
    if (!parsedYt.valid || !parsedYt.videoId || !parsedYt.canonicalUrl) {
      throw new Error(parsedYt.error || 'Invalid YouTube URL format');
    }
    youtubeVideoId = parsedYt.videoId;
    youtubeUrl = parsedYt.canonicalUrl;
    if (!thumbnailUrl && youtubeVideoId) {
      thumbnailUrl = `https://img.youtube.com/vi/${youtubeVideoId}/hqdefault.jpg`;
    }
  }

  const rawSegments = input.transcript ? parseRawSegments(input.transcript) : [];
  let segments: TranscriptSegment[] = [];
  let transcriptStatus: TranscriptStatus = 'unavailable';
  let extractionStatus: string | null = input.extractionStatus || null;

  if (rawSegments.length > 0) {
    const validation = validateTranscriptSegments(rawSegments, input.durationSeconds);
    if (!validation.valid) {
      throw new Error(`Transcript rejected: ${validation.error}`);
    }
    segments = validation.segments!;
    transcriptStatus = 'ready';
    extractionStatus = extractionStatus || 'ready';
  } else if (input.sourceType === 'youtube' || input.storagePath) {
    transcriptStatus = 'processing';
    extractionStatus = 'processing';
  }

  const transcriptJson = segments.length > 0 ? JSON.stringify(segments) : null;
  const initialStatus = transcriptStatus === 'processing' ? 'processing' : 'ready';

  const maxSegmentEnd = segments.reduce((max, s) => Math.max(max, s.end), 0);
  const duration = input.durationSeconds || maxSegmentEnd || 0;

  const now = new Date();
  await prisma.$executeRawUnsafe(
    `INSERT INTO videos (
      id, userId, title, sourceType, youtubeUrl, youtubeVideoId, storagePath, fileUrl,
      status, durationSeconds, thumbnailUrl, transcriptStatus, transcriptJson, errorMessage,
      channelName, durationSource, captionLanguage, captionLanguageName, captionKind,
      isAutoGenerated, captionProvider, extractionStatus,
      createdAt, updatedAt
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
    id,
    input.userId,
    input.title,
    input.sourceType,
    youtubeUrl,
    youtubeVideoId,
    input.storagePath || null,
    input.fileUrl || null,
    initialStatus,
    duration,
    thumbnailUrl,
    transcriptStatus,
    transcriptJson,
    null,
    input.channelName || null,
    input.durationSource || null,
    input.captionLanguage || null,
    input.captionLanguageName || null,
    input.captionKind || null,
    input.isAutoGenerated === undefined || input.isAutoGenerated === null ? null : (input.isAutoGenerated ? 1 : 0),
    input.captionProvider || null,
    extractionStatus,
    now,
    now
  );

  const video = await getVideoById(id, input.userId);
  if (!video) throw new Error('Failed to create video record');

  // If transcript segments were provided immediately, ingest them into RAG
  if (segments.length > 0) {
    try {
      await ingestVideoTranscriptToRAG(video, segments);
    } catch (ingestErr) {
      console.warn('Initial RAG ingestion warning:', ingestErr);
    }
  }

  return video;
}

