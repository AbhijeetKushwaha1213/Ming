// Lightweight deterministic Devanagari-to-Latin phonetic transliterator for server-side overlap checks
const DEV_CONSONANTS: Record<string, string> = {
  'क': 'k', 'ख': 'kh', 'ग': 'g', 'घ': 'gh', 'ङ': 'ng',
  'च': 'ch', 'छ': 'chh', 'ज': 'j', 'झ': 'jh', 'ञ': 'ny',
  'ट': 't', 'ठ': 'th', 'ड': 'd', 'ढ': 'dh', 'ण': 'n',
  'त': 't', 'थ': 'th', 'द': 'd', 'ध': 'dh', 'न': 'n',
  'प': 'p', 'फ': 'ph', 'ब': 'b', 'भ': 'bh', 'म': 'm',
  'य': 'y', 'र': 'r', 'ल': 'l', 'व': 'v', 'श': 'sh',
  'ष': 'sh', 'स': 's', 'ह': 'h',
  'क़': 'q', 'ख़': 'kh', 'ग़': 'gh', 'ज़': 'z', 'ड़': 'r', 'ढ़': 'rh', 'फ़': 'f', 'य़': 'y',
};
const DEV_VOWELS: Record<string, string> = {
  'अ': 'a', 'आ': 'aa', 'इ': 'i', 'ई': 'ee', 'उ': 'u', 'ऊ': 'oo',
  'ऋ': 'ri', 'ए': 'e', 'ऐ': 'ai', 'ओ': 'o', 'औ': 'au', 'ऑ': 'o', 'ऍ': 'e',
};
const DEV_MATRAS: Record<string, string> = {
  'ा': 'a', 'ि': 'i', 'ी': 'i', 'ु': 'u', 'ू': 'u',
  'ृ': 'ri', 'े': 'e', 'ै': 'ai', 'ो': 'o', 'ौ': 'au', 'ॉ': 'o', 'ॅ': 'e',
};

function transliterateDevanagariToLatin(text: string): string {
  if (!text || !/[\u0900-\u097F]/.test(text)) return '';
  const out: string[] = [];
  for (let i = 0; i < text.length; i++) {
    let ch = text[i];
    let nxt = i + 1 < text.length ? text[i + 1] : '';
    if (nxt === '\u093C' && DEV_CONSONANTS[ch + nxt]) {
      ch = ch + nxt;
      i++;
      nxt = i + 1 < text.length ? text[i + 1] : '';
    }
    if (DEV_CONSONANTS[ch]) {
      out.push(DEV_CONSONANTS[ch]);
      if (nxt === '\u094D') {
        i++;
      } else if (DEV_MATRAS[nxt] || nxt === '\u0902' || nxt === '\u0901') {
        // vowel follows
      } else if (!nxt || !/[\u0900-\u097F]/.test(nxt)) {
        // drop trailing schwa
      } else {
        out.push('a');
      }
    } else if (DEV_VOWELS[ch]) {
      out.push(DEV_VOWELS[ch]);
    } else if (DEV_MATRAS[ch]) {
      out.push(DEV_MATRAS[ch]);
    } else if (ch === '\u0902' || ch === '\u0901') {
      out.push('n');
    } else if (ch === '\u0903') {
      out.push('h');
    } else if (ch === '\u094D') {
      // halant
    } else if (/[\x20-\x7E]/.test(ch)) {
      out.push(ch);
    } else {
      out.push(' ');
    }
  }
  const raw = out.join('');
  return `${raw} ${raw.replace(/ph/g, 'f')}`.replace(/\s+/g, ' ').trim();
}

