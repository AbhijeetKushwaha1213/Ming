export type VideoSourceType = 'youtube' | 'upload';
export type VideoStatus = 'pending' | 'processing' | 'ready' | 'failed';
export type TranscriptStatus = 'pending' | 'processing' | 'ready' | 'failed' | 'unavailable';

export interface TranscriptSegment {
  start: number; // in seconds
  end: number;   // in seconds
  text: string;
  topic?: string;
  subtopic?: string;
}

export interface VideoRecord {
  id: string;
  userId: string;
  title: string;
  sourceType: VideoSourceType;
  youtubeUrl?: string | null;
  youtubeVideoId?: string | null;
  storagePath?: string | null;
  fileUrl?: string | null;
  status: VideoStatus;
  durationSeconds: number;
  thumbnailUrl?: string | null;
  transcriptStatus: TranscriptStatus;
  transcriptJson?: string | null;
  errorMessage?: string | null;
  channelName?: string | null;
  durationSource?: string | null;
  captionLanguage?: string | null;
  captionLanguageName?: string | null;
  captionKind?: string | null;
  isAutoGenerated?: boolean | null;
  captionProvider?: string | null;
  extractionStatus?: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface VideoCitation {
  chunk_id: string;
  evidence_id?: string;
  source_id?: string;
  document_id?: string;
  source_type: string;
  page_number?: number | null;
  slide_number?: number | null;
  timestamp_start?: number | null;
  timestamp_end?: number | null;
  seek_seconds?: number;
  formatted_timestamp?: string;
  citation_label: string;
  snippet?: string;
  english_gloss?: string | null;
  caption_language?: string | null;
  caption_kind?: string | null;
  is_auto_generated?: boolean | null;
}

export interface VideoAskResponse {
  success: boolean;
  videoId: string;
  question: string;
  response: string;
  citations: VideoCitation[];
  grounded: boolean;
  insufficient_evidence?: boolean;
  partial_answer?: boolean;
  evidence_coverage_score?: number;
}
